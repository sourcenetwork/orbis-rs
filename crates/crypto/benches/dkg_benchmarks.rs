use criterion::{black_box, criterion_group, criterion_main, BenchmarkId, Criterion};
use std::time::Duration;

use crypto::r#trait::{DistributedShare, Dkg, DkgMode};

#[cfg(feature = "bls12-381")]
#[path = "bls12_381/dkg.rs"]
mod bls12_381_dkg;

#[cfg(feature = "decaf377")]
#[path = "decaf377/dkg.rs"]
mod decaf377_dkg;

// ---------------------------------------------------------------------------
// Generic benchmark infrastructure
// ---------------------------------------------------------------------------

/// A fully initialized DKG node that has completed through Phase 1 (polynomial
/// generated, commitment ready) and received all other nodes' commitments.
/// Ready for share generation and receipt.
pub struct PreparedNode<D: Dkg> {
    pub node: Box<D>,
}

/// All the data needed to benchmark individual DKG operations.
pub struct DkgBenchFixture<D: Dkg> {
    /// Nodes after Phase 1 with all commitments exchanged.
    pub prepared_nodes: Vec<PreparedNode<D>>,
    /// Shares generated by each node (outer index = source node).
    pub all_shares: Vec<Vec<DistributedShare<D::ShareValue>>>,
    pub threshold: usize,
    pub total_nodes: usize,
}

/// Implement this trait to plug a Dkg implementation into the generic
/// benchmark suite.
pub trait DkgBenchSetup {
    type Node: Dkg + Clone;

    /// Create a single uninitialised node (polynomial not yet generated).
    fn create_node(
        id: u32,
        threshold: usize,
        total_nodes: usize,
        session_id: u128,
    ) -> Box<Self::Node>;

    /// Build a full fixture: run Phase 1, exchange commitments, generate shares.
    fn create_fixture(threshold: usize, total_nodes: usize) -> DkgBenchFixture<Self::Node> {
        use rand_core::{OsRng, RngCore};
        let mut rng = OsRng;
        let mut session_id_bytes = [0u8; 16];
        rng.fill_bytes(&mut session_id_bytes);
        let session_id = u128::from_le_bytes(session_id_bytes);

        let mut nodes: Vec<Box<Self::Node>> = (1..=total_nodes as u32)
            .map(|id| Self::create_node(id, threshold, total_nodes, session_id))
            .collect();

        // Phase 1: generate polynomials
        for node in &mut nodes {
            node.generate_polynomial(DkgMode::Fresh).unwrap();
        }

        // Exchange commitments
        let commitments: Vec<(u32, <Self::Node as Dkg>::PolynomialCommitment)> = nodes
            .iter()
            .map(|n| (n.node_id(), n.commitment().clone()))
            .collect();

        for node in &mut nodes {
            for (from_id, cmt) in &commitments {
                if *from_id != node.node_id() {
                    node.receive_commitment(*from_id, cmt.clone()).unwrap();
                }
            }
        }

        // Phase 2: generate shares
        let all_shares: Vec<Vec<DistributedShare<_>>> =
            nodes.iter().map(|n| n.generate_shares().unwrap()).collect();

        let prepared_nodes = nodes
            .into_iter()
            .map(|node| PreparedNode { node })
            .collect();

        DkgBenchFixture {
            prepared_nodes,
            all_shares,
            threshold,
            total_nodes,
        }
    }
}

/// Register all DKG benchmarks for a given `DkgBenchSetup` implementation.
fn run_dkg_benchmarks<S: DkgBenchSetup>(c: &mut Criterion, prefix: &str) {
    // -- generate_polynomial --------------------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/generate_polynomial"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| {
                    let mut node = S::create_node(1, black_box(t), black_box(n), 0);
                    node.generate_polynomial(DkgMode::Fresh).unwrap();
                })
            });
        }

        group.finish();
    }

    // -- generate_shares ------------------------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/generate_shares"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            let fixture = S::create_fixture(t, n);

            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| fixture.prepared_nodes[0].node.generate_shares().unwrap())
            });
        }

        group.finish();
    }

    // -- receive_share (includes commitment verification) ---------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/receive_share"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            let fixture = S::create_fixture(t, n);

            // Benchmark node 0 receiving a share from node 1.
            // Each iteration needs a fresh nonce, so we generate a new share
            // in the setup phase via iter_batched.
            let node_0_id = fixture.prepared_nodes[0].node.node_id();
            let template_share = fixture.all_shares[1]
                .iter()
                .find(|s| s.to_id == node_0_id)
                .unwrap()
                .clone();

            let base_node = &fixture.prepared_nodes[0].node;

            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter_batched(
                    || {
                        // Setup (untimed): clone node + give share a fresh nonce
                        let mut share = template_share.clone();
                        use rand_core::{OsRng, RngCore};
                        OsRng.fill_bytes(&mut share.nonce);
                        (base_node.clone(), share)
                    },
                    |(mut node, share)| {
                        node.receive_share(black_box(share)).unwrap();
                    },
                    criterion::BatchSize::SmallInput,
                )
            });
        }

        group.finish();
    }

    // -- compute_secret_share -------------------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/compute_secret_share"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            // Build a fully-completed node (all shares received)
            let fixture = S::create_fixture(t, n);
            let mut node = fixture.prepared_nodes.into_iter().next().unwrap().node;

            // Deliver all shares destined for this node
            let node_id = node.node_id();
            for shares_from in &fixture.all_shares {
                for share in shares_from {
                    if share.to_id == node_id && share.from_id != node_id {
                        node.receive_share(share.clone()).unwrap();
                    }
                }
            }

            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| node.compute_secret_share().unwrap())
            });
        }

        group.finish();
    }

    // -- compute_aggregate_public_key -----------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/compute_aggregate_public_key"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            let fixture = S::create_fixture(t, n);

            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| {
                    fixture.prepared_nodes[0]
                        .node
                        .compute_aggregate_public_key()
                        .unwrap()
                })
            });
        }

        group.finish();
    }

    // -- compute_public_polynomial --------------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/compute_public_polynomial"));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            let fixture = S::create_fixture(t, n);

            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| {
                    fixture.prepared_nodes[0]
                        .node
                        .compute_public_polynomial()
                        .unwrap()
                })
            });
        }

        group.finish();
    }

    // -- full DKG ceremony (end-to-end) ---------------------------------------
    {
        let mut group = c.benchmark_group(format!("{prefix}/full_ceremony"));
        group.measurement_time(Duration::from_secs(20));

        for &(t, n) in &[(2, 3), (3, 5), (5, 9)] {
            group.bench_function(BenchmarkId::new("t_of_n", format!("{t}_of_{n}")), |b| {
                b.iter(|| {
                    let mut nodes: Vec<Box<S::Node>> = (1..=n as u32)
                        .map(|id| S::create_node(id, t, n, 1))
                        .collect();

                    // Phase 1
                    for node in &mut nodes {
                        node.generate_polynomial(DkgMode::Fresh).unwrap();
                    }

                    // Exchange commitments
                    let commitments: Vec<(u32, _)> = nodes
                        .iter()
                        .map(|n| (n.node_id(), n.commitment().clone()))
                        .collect();
                    for node in &mut nodes {
                        for (from_id, cmt) in &commitments {
                            if *from_id != node.node_id() {
                                node.receive_commitment(*from_id, cmt.clone()).unwrap();
                            }
                        }
                    }

                    // Phase 2: generate + distribute shares
                    let all_shares: Vec<Vec<DistributedShare<_>>> =
                        nodes.iter().map(|n| n.generate_shares().unwrap()).collect();

                    for shares_from in &all_shares {
                        for share in shares_from {
                            if share.from_id != share.to_id {
                                let recipient = nodes
                                    .iter_mut()
                                    .find(|n| n.node_id() == share.to_id)
                                    .unwrap();
                                recipient.receive_share(share.clone()).unwrap();
                            }
                        }
                    }

                    // Phase 4: compute results
                    let _pk = nodes[0].compute_aggregate_public_key().unwrap();
                    let _poly = nodes[0].compute_public_polynomial().unwrap();
                    for node in &nodes {
                        black_box(node.compute_secret_share().unwrap());
                    }
                })
            });
        }

        group.finish();
    }
}

// ---------------------------------------------------------------------------
// Benchmark registration (one curve per build; features are mutually exclusive)
// ---------------------------------------------------------------------------
fn run_all_dkg_benchmarks(c: &mut Criterion) {
    #[cfg(feature = "bls12-381")]
    run_dkg_benchmarks::<bls12_381_dkg::Bls12381DkgBench>(c, "bls12_381");
    #[cfg(feature = "decaf377")]
    run_dkg_benchmarks::<decaf377_dkg::Decaf377DkgBench>(c, "decaf377");
}

criterion_group!(benches, run_all_dkg_benchmarks);
criterion_main!(benches);
